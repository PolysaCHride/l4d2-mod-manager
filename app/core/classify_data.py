_LOD_SUFFIXES = ("_light", "_low", "_lod", "_hq")

def lookup_stem(stem):
    """文件 stem -> [(类别, 物品)]。带 LOD 变体后缀时自动回退到主名。"""
    stem = stem.lower()
    out = WHITELIST_STEMS.get(stem)
    out = list(out) if out else []
    if out:
        return list(out)
    for suf in _LOD_SUFFIXES:
        if stem.endswith(suf):
            out = WHITELIST_STEMS.get(stem[: -len(suf)])
            if out:
                return list(out)
    return None

def match_rules(paths):
    """路径前缀/正则规则匹配。返回 {(类别, 物品)}；无命中返回空集。"""
    out = set()
    for p in paths:
        for prefix, cat, item in PREFIX_RULES:
            if p.startswith(prefix):
                out.add((cat, item))
        for rx, cat, item in REGEX_RULES:
            try:
                if re.search(rx, p):
                    out.add((cat, item))
            except re.error:
                pass
    return out
